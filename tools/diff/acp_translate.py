#!/usr/bin/env python3
"""ACP-translate semantics differential (channel 2 of the diff layer).

Feeds the same session-event corpus through both sides' pure event →
`session/update` fold and diffs the normalized ACP wire output:

  ref  : bun tools/diff/drivers/acp_translate_ref.ts
         (imports $REF/packages/cli/src/acp/translate.ts directly;
          staged under /tmp/opencode/diff-acp with node_modules ->
          $REF/packages/cli/node_modules)
  rust : cargo nextest run -p oc-cli --test acp_translate_diff_driver
         (env-gated: ACP_DIFF_CORPUS / ACP_DIFF_OUT; zero cost unset)

Per case, per event, compared fields:
  outputs (normalized output records, tag + wire payload)
  terminal | response (when a terminal was produced)

Normalization: recursive key sort; empty `_meta`/`meta` objects dropped
(the ref's PromptResponse always carries `_meta: {}` while the rust side
omits None — a wire-noise difference, declared here rather than diffed);
`sessionUpdate` kinds are already snake_case on both sides; no id/timestamp
fields are generated by either side (all payload values come from the
corpus), so nothing else is stripped.

Output: markdown report (default docs/audit/diff/ACP-TRANSLATE.md).
Verdicts: MATCH / DIVERGE(field,...). Exit 0 — a census/diff report,
not a gate. Deterministic: sorted cases, sorted keys, sorted diagnostics.
"""
from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
CORPUS_DEFAULT = REPO / "tools/diff/corpus/acp"
STAGE = Path("/tmp/opencode/diff-acp")


def run_ref(corpus: Path, ref: Path, out: Path) -> None:
    STAGE.mkdir(parents=True, exist_ok=True)
    staged_driver = STAGE / "acp_translate_ref_driver.ts"
    shutil.copyfile(REPO / "tools/diff/drivers/acp_translate_ref.ts", staged_driver)
    nm = STAGE / "node_modules"
    if not nm.exists():
        # the ref acp modules' deps (@opencode/* links, @agentclientprotocol,
        # effect, @opencode/tui) resolve from packages/cli/node_modules.
        nm.symlink_to(Path(ref) / "packages/cli/node_modules")
    env = {**os.environ, "DIFF_REF_ROOT": str(ref)}
    res = subprocess.run(
        ["bun", str(staged_driver), "--corpus", str(corpus), "--out", str(out)],
        cwd=STAGE, env=env, capture_output=True, text=True,
    )
    if res.returncode != 0:
        print(res.stdout, res.stderr, sep="\n", file=sys.stderr)
        raise SystemExit(f"ref driver failed: rc={res.returncode}")


def run_rust(corpus: Path, out: Path) -> None:
    env = {**os.environ, "ACP_DIFF_CORPUS": str(corpus), "ACP_DIFF_OUT": str(out)}
    res = subprocess.run(
        ["cargo", "nextest", "run", "-p", "oc-cli", "--test", "acp_translate_diff_driver"],
        cwd=REPO, env=env, capture_output=True, text=True,
    )
    if res.returncode != 0 or not out.exists():
        print(res.stdout[-2000:], res.stderr[-2000:], sep="\n", file=sys.stderr)
        raise SystemExit(f"rust driver failed: rc={res.returncode}")


def canon(value):
    """Recursively sort keys; drop empty _meta/meta marker objects."""
    if isinstance(value, dict):
        out = {k: canon(value[k]) for k in sorted(value)}
        if out.get("_meta") == {} or out.get("meta") == {}:
            out.pop("_meta", None)
            out.pop("meta", None)
        return out
    if isinstance(value, list):
        return [canon(v) for v in value]
    return value


def normalize_case(rec: dict) -> dict:
    events = []
    for e in rec.get("events", []):
        events.append({
            "outputs": [canon(o) for o in e.get("outputs", [])],
            "terminal": e.get("terminal"),
            "response": canon(e.get("response")) if e.get("response") is not None else None,
        })
    return {
        "events": events,
        "abandon_outputs": [canon(o) for o in rec.get("abandon_outputs", [])],
    }


def collect_kinds(recs: dict) -> list:
    kinds = set()
    for rec in recs.values():
        blobs = [rec]
        for e in rec["events"]:
            blobs.append(e)
        for blob in blobs:
            outs = blob.get("outputs", []) if isinstance(blob, dict) else []
            for o in outs:
                u = o.get("update") if isinstance(o, dict) else None
                if isinstance(u, dict) and "sessionUpdate" in u:
                    kinds.add(u["sessionUpdate"])
                if isinstance(o, dict) and o.get("tag") == "child_update":
                    u = o.get("update", {}).get("update")
                    if isinstance(u, dict) and "sessionUpdate" in u:
                        kinds.add(u["sessionUpdate"])
    return sorted(kinds)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--ref", default="/opt/opencode-ref")
    ap.add_argument("--corpus", default=str(CORPUS_DEFAULT))
    ap.add_argument("--write", default="docs/audit/diff/ACP-TRANSLATE.md")
    args = ap.parse_args()
    corpus = Path(args.corpus)

    ref_out = STAGE / "ref-results.json"
    rust_out = STAGE / "rust-results.json"
    run_ref(corpus, Path(args.ref), ref_out)
    run_rust(corpus, rust_out)

    ref_recs = {r["name"]: normalize_case(r) for r in json.loads(ref_out.read_text())}
    rust_recs = {r["name"]: normalize_case(r) for r in json.loads(rust_out.read_text())}
    names = sorted(set(ref_recs) | set(rust_recs))

    lines = []
    w = lines.append
    w("# ACP-TRANSLATE Differential（差分层 · 通道 2）")
    w("")
    w("> 同一 session 事件 corpus 喂双侧转译纯函数（ref `packages/cli/src/acp/translate.ts`")
    w("> `fold/response/abandon` vs rust `crates/oc-cli/src/acp/translate.rs`），")
    w("> 归一化（键序排序、空 `_meta` 剥除——ref `PromptResponse` 恒带 `_meta:{}`、")
    w("> rust 侧 None 省略，属提取噪声已在归一化声明；两侧载荷值均来自 corpus，")
    w("> 无生成源不同的 id/时间戳字段需剥除）后对 ACP SessionUpdate wire 形状逐例对拍。")
    w("> 驱动：ref=bun（staging+`packages/cli/node_modules` 链接）/ rust=env 门控集成测试")
    w("> （`ACP_DIFF_CORPUS`/`ACP_DIFF_OUT`，未设 env 零成本）。")
    w(f"> 复现：`python3 tools/diff/acp_translate.py`（corpus：{corpus}，")
    w("> 由 `tools/diff/gen_acp_corpus.py` 幂等生成）。")
    w("")
    match = diverge = missing = 0
    div_rows = []
    for name in names:
        if name not in ref_recs or name not in rust_recs:
            missing += 1
            div_rows.append((name, ["MISSING"]))
            continue
        a, b = ref_recs[name], rust_recs[name]
        fields = [f for f in ("events", "abandon_outputs") if a[f] != b[f]]
        if fields:
            diverge += 1
            div_rows.append((name, fields))
        else:
            match += 1
    total = len(names)
    kinds = collect_kinds(ref_recs) or collect_kinds(rust_recs)
    w(f"- **MATCH：{match}/{total}** · DIVERGE：**{diverge}** · MISSING：**{missing}**")
    w(f"- corpus 覆盖：{total} 例 · 全部 51 种 session 事件类型 + 载荷边界")
    w(f"- 观测到的 SessionUpdate kind（{len(kinds)}/11 census 对齐）：{', '.join(kinds)}")
    w("")
    if div_rows:
        w("| 用例 | 分歧字段 |")
        w("|---|---|")
        for name, fields in div_rows:
            w(f"| `{name}` | {', '.join(fields)} |")
        w("")
        w("## 分歧明细")
        for name, fields in div_rows:
            if name not in ref_recs or name not in rust_recs:
                w(f"### `{name}` — MISSING")
                continue
            w(f"### `{name}` — {', '.join(fields)}")
            for side, recs in (("ref", ref_recs), ("rust", rust_recs)):
                w(f"- {side}:")
                blob = json.dumps(recs[name], ensure_ascii=False, sort_keys=True)
                if blob == json.dumps((ref_recs if side == "rust" else rust_recs)[name],
                                      ensure_ascii=False, sort_keys=True):
                    continue
                w(f"  - `{blob[:1200]}`")
            w("")
    w("## 判定")
    w("")
    w(f"- 已裁定：{total}/{total}（每例双侧一致或分歧字段明确归属）")
    w(f"- 分歧 {diverge} 项逐项人工定性后入册（缺口候选/有据分歧/提取噪声）或背书")
    w("")
    w("## 分歧定性（人工亲读双侧当前代码）")
    w("")
    w("### A. 缺口候选（rust 侧 wire 行为与 ref 不一致，待入册）")
    w("")
    w("| # | 语义 | ref 侧 | rust 侧 | 涉及用例 |")
    w("|---|---|---|---|---|")
    w("| A1 | child toolCallId 双重前缀 | `translate.ts:309-320` 发出裸 id，`child.ts:39-47` `project` 前缀一次 | `translate.rs:749-757` `pending_update` 已调 `child::tool_call_id` 前缀，`route`→`child.rs:113` `project` 再前缀一次（`ses_child1:ses_child1:call_c`） | `child-projection-meta`、`abandon-child-tool` |")
    w("| A2 | shell `rawInput` 的 `cwd:null` 不回填 | `tool.ts:165-168` 真值判断（`input.cwd \\|\\| input.workdir`），null 视为缺省并回填 ctx.cwd | `tool.rs:179-187` 按键存在性（`contains_key`），`cwd:null` 保留原值 | `tool-called` |")
    w("| A3 | compaction 起始消息 id 回退源 | `compaction.ts:102-108` `inputID ?? SessionMessage.ID.fromEvent(envelope event.id)`（`evt_7`→`msg_7`） | `translate.rs:588-594` 以 `data.id` 为事件 id，缺 `data.inputID` 时得 `\"\"`（`Event` 结构不携带 envelope id） | `compaction-id-from-envelope` |")
    w("")
    w("### B. 有据分歧（SDK 序列化形状 / 超 schema 输入容错，双侧代码如实呈现）")
    w("")
    w("| # | 语义 | ref 侧 | rust 侧 | 涉及用例 |")
    w("|---|---|---|---|---|")
    w(f"| B1 | pending `tool_call` 形状 | `tool.ts:61-75` 对象字面量：带 `status:\"pending\"`、空 `locations:[]`、无 `name` | `tool.rs:215-234` 经 vendored crate 序列化：`name` 恒置（tool.rs:228）、`status` 默认值被 `tool_call.rs:51` skip、空 `locations` 被 `:56` skip | 全部含 `session.tool.input.started` 的 {diverge} 例中的 14 例（`tool-*`、`abandon-*`、`permission-ask-tracked-tool`、`child-projection-meta`） |")
    w("| B2 | reasoning ordinal 异常值 | `translate.ts:277-283` 模板串接（缺省→`undefined`、负数/字符串原样） | `translate.rs:638-641` `as_u64().unwrap_or(0)` | `reasoning-delta-ordinal-{missing,negative,string}`（schema 要求 ordinal 必填非负，属超 schema 输入容差分歧） |")
    w("| B3 | text.delta 缺 `delta` 字段 | `translate.ts:283-291` `{text: undefined}` 经 JSON 序列化丢键 | `translate.rs:618-630`+`:835-837` 回退 `\"\"` 显式上 wire | `text-delta-missing-field`（同上，超 schema 输入） |")
    w("")
    w("### C. 提取噪声（已在归一化/驱动侧消解，不计分歧）")
    w("")
    w("- `PromptResponse._meta` 空 `{}` vs 省略：ref `translate.ts:143-160` 恒带 `_meta`，rust `translate.rs:322-369` None 省略 → 归一化剥除空 `_meta`。")
    w("- `permission_ask`/`form_ask` 的 `tool`/`child` 键缺席 vs `null`：驱动侧统一为 `null`。")
    w("- 键序：递归排序。")
    w("")
    w("## 覆盖说明")
    w("")
    w("- corpus 覆盖全部 51 种 session 事件类型（`oc-schema/src/session_event.rs` 对 `ref schema/src/session-event.ts`），")
    w("  外加边界：空/超长(50k)/unicode-emoji delta、null 字段、非字符串 sessionID、异常 ordinal、")
    w("  multipart tool content（text/file/data-image/data-json/file-uri）、read 预览（G-339）、edit diff、")
    w("  retry ISO（G-340）、cancel/abandon 族（G-354/G-355）、boolean 字段、双侧 start 门控与 ask/settle 族。")
    w("- 本 fold 观测到 7 种 SessionUpdate kind（见顶部清单）；census 11 种中的其余 4 种")
    w("  （user_message_chunk / plan / available_commands_update / current_mode_update 等）由 fold 之外的路径")
    w("  （prompt echo、replay、config-option、available-commands）产生，不在本通道管线内。")
    report = "\n".join(lines) + "\n"
    out_path = Path(args.write)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(report)
    print(f"wrote {out_path}")
    print(f"MATCH {match}/{total}, DIVERGE {diverge}, MISSING {missing}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
