def log(event: str, **fields):
    line = json.dumps({"t": round(time.time(), 3), "event": event, **fields},
                      ensure_ascii=False)
    with LOG_LOCK:
        stream = LOG if LOG else sys.stdout
        print(line, file=stream, flush=True)


# ---------------------------------------------------------------------------
# Pacing (W5 timing fidelity)
# ---------------------------------------------------------------------------

TTFT_TIERS_MS = (300, 1500, 4000)
TPS_TIERS = (20, 60, 120)


def parse_pace(spec):
    """--pace spec → dict(mode, seed, ttft_ms, tps)."""
    if spec == "instant":
        return {"mode": "instant"}
    if spec == "frames":
        return {"mode": "frames"}
    if spec.startswith("synthetic"):
        rest = spec.split(":", 1)[1] if ":" in spec else ""
        out = {"mode": "synthetic", "seed": 0, "ttft_ms": None, "tps": None}
        for part in rest.split(":"):
            if not part:
                continue
            if part.startswith("seed="):
                out["seed"] = int(part[5:])
            elif part.startswith("ttft="):
                out["ttft_ms"] = int(part[5:])
            elif part.startswith("tps="):
                out["tps"] = int(part[4:])
            else:
                raise SystemExit(f"--pace: unknown synthetic param {part!r}")
        return out
    raise SystemExit(f"--pace: unknown mode {spec!r}")


def synthetic_schedule(digest, seed):
    """Deterministic (ttft_ms, tps) tier pair for a request digest."""
    mix = int(hashlib.sha256(f"{digest}:{seed}".encode()).hexdigest()[:8], 16)
    return TTFT_TIERS_MS[mix % len(TTFT_TIERS_MS)], TPS_TIERS[(mix >> 8) % len(TPS_TIERS)]


def split_sse_frames(body):
    """Split an SSE body into event frames (each blob keeps its \n\n)."""
    frames = []
    start = 0
    while True:
        at = body.find("\n\n", start)
        if at == -1:
            break
        frames.append(body[start:at + 2])
        start = at + 2
    if start < len(body):
        frames.append(body[start:])
    return frames


def _frame_text_bytes(blob):
    """Payload text size of one SSE frame (0 for non-delta frames)."""
    for line in blob.splitlines():
        if line.startswith("data:"):
            payload = line[5:].strip()
            if not payload:
                continue
            try:
                doc = json.loads(payload)
            except ValueError:
                continue
            delta = doc.get("delta") if isinstance(doc, dict) else None
            if isinstance(delta, dict) and delta.get("type") == "text_delta":
                return len(delta.get("text") or "")
    return 0


def build_schedule(digest, resp_body_text, pace):
    """[(blob_bytes, delay_ms_before)] for the body under the pace mode."""
    if pace["mode"] == "instant":
        return [(resp_body_text.encode(), 0)]
    if pace["mode"] == "frames":
        # v1 cassettes carry no frames — degrade to instant (documented
        # fallback; W5 review Important-1: the caller previously
        # crashed summing None).
        return [(resp_body_text.encode(), 0)]
    ttft, tps = synthetic_schedule(digest, pace["seed"])
    if pace["ttft_ms"] is not None:
        ttft = pace["ttft_ms"]
    if pace["tps"] is not None:
        tps = pace["tps"]
    frames = split_sse_frames(resp_body_text)
    schedule = []
    seen_delta = False

    def emit_delta_frame(payload_line_template, text, delay):
        # Re-frame one text_delta into per-token sub-events (transport
        # re-chunking: SSE consumers must accept arbitrary event
        # chunking; BOTH pair ends receive identical bytes).
        step = 3
        for i in range(0, len(text), step):
            chunk = text[i:i + step]
            blob = payload_line_template.replace("__TEXT__", chunk) + "\n\n"
            d = delay if i == 0 else max(1, round(len(chunk) / tps * 1000))
            schedule.append((blob.encode(), d))

    for blob in frames:
        template = None
        text = None
        for line in blob.splitlines():
            if line.startswith("data:"):
                payload = line[5:].strip()
                try:
                    doc = json.loads(payload)
                except ValueError:
                    continue
                delta = doc.get("delta") if isinstance(doc, dict) else None
                if isinstance(delta, dict) and delta.get("type") == "text_delta":
                    text = delta.get("text") or ""
                    # Rebuild the wire line with the text swapped out.
                    doc["delta"]["text"] = "__TEXT__"
                    template = "data: " + json.dumps(doc, separators=(",", ":"))
        if template is None:
            schedule.append((blob.encode(), 0))
            continue
        delay = ttft if not seen_delta else 0
        seen_delta = True
        emit_delta_frame(template, text, delay)
    if not schedule:
        schedule = [(resp_body_text.encode(), 0)]
    return schedule


def frames_from_schedule(schedule):
    """v2 cassette `frames` for a computed schedule (recorded timing)."""
    return [{"blob": blob.decode("utf-8", "replace"), "delay_ms": delay}
            for blob, delay in schedule]


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):  # silence default stderr chatter
        pass

    # -- helpers ----------------------------------------------------------
    def _send(self, status, body: bytes, content_type="application/json"):
        self.send_response(status)
        self.send_header("content-type", content_type)
        self.send_header("content-length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
        self.wfile.flush()

    def _diagnostic(self, digest, key, path):
        diag = {
            "error": "replay-gateway: no cassette matched (strict mode)",
            "request_sha256": digest,
            "normalized": {
                "model": key["model"],
                "message_count": len(key["messages"] or []),
                "tool_count": len(key["tools"] or []),
                "system": (key["system"] if isinstance(key["system"], str)
                           else _canon(key["system"])[:400]),
            },
            "path": path,
            "hint": "seed with --seed-reply/--record-dir, or extend --corpus",
        }
        self._send(404, json.dumps(diag, indent=2).encode())

    # -- GET ---------------------------------------------------------------
    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/__stats":
            STATS.corpus_size = CORPUS.count if CORPUS else 0
            self._send(200, json.dumps(STATS.snapshot(), indent=2).encode())
            return
        if parsed.path.rstrip("/").endswith("/models"):
            # A tiny model list keeps SDK probes alive; the harness asserts
            # on the SERVER's model API, never here.
            self._send(200, json.dumps({"data": []}).encode())
            return
        self._send(404, b'{"error":"replay-gateway: unknown GET route"}')

    # -- shared serve --------------------------------------------------------
    def _serve_schedule(self, status, ctype, schedule):
        self.send_response(status)
        self.send_header("content-type", ctype)
        self.send_header("content-length", str(sum(len(b) for b, _ in schedule)))
        self.send_header("cache-control", "no-store")
        self.end_headers()
        for blob, delay in schedule:
            if delay:
                time.sleep(delay / 1000.0)
            self.wfile.write(blob)
            self.wfile.flush()

    def _serve_interaction(self, digest, cassette, inter, extra=None):
        resp = inter.get("response") or {}
        resp_body = (resp.get("body") or "")
        if isinstance(resp_body, bytes):
            resp_body = resp_body.decode("utf-8", "replace")
        ctype = (resp.get("headers") or {}).get("content-type", "application/json")
        schedule = None
        if ARGS.pace["mode"] == "frames":
            raw_frames = resp.get("frames")
            if isinstance(raw_frames, list) and raw_frames:
                candidate = []
                for frame in raw_frames:
                    blob = (frame or {}).get("blob", "")
                    delay = (frame or {}).get("delay_ms", 0) or 0
                    if isinstance(blob, str):
                        candidate.append((blob.encode(), int(delay)))
                joined = "".join(f.decode("utf-8", "replace") for f, _ in candidate)
                if candidate and joined == resp_body:
                    schedule = candidate
        if schedule is None:
            schedule = build_schedule(digest, resp_body, ARGS.pace)
        self._serve_schedule(resp.get("status", 200), ctype, schedule)
        STATS.note_hit()
        log("hit", sha256=digest, cassette=cassette, status=resp.get("status"),
            pace=ARGS.pace["mode"], frames=len(schedule), **(extra or {}))

    # -- W7 turn-anchored main-loop POST --------------------------------------
    def _do_turn_post(self, path, body, key, digest):
        turn = TURN_STATE.current_and_advance()
        shape = shape_digest(key)
        inter, cassette, event = TURNCORPUS.lookup_main(turn, shape)
        if inter is not None:
            self._serve_interaction(digest, cassette, inter,
                                    {"turn": turn, "match": event})
            return
        # Strict miss on the ordinal: the --seed-turns bootstrap serves
        # the scripted body for this turn and records the cassette WITH
        # the turn tag (the committed corpus replays strictly).
        if ARGS.seed_turns and ARGS.record_dir and key["model"]:
            seed_path = _seed_turn_file(ARGS.seed_turns, turn)
            if seed_path:
                seed_text = open(seed_path, encoding="utf-8").read()
                schedule = build_schedule(digest, seed_text, ARGS.pace)
                cassette_doc = {
                    "version": 2,
                    "metadata": {
                        "name": f"seeded/turn-{turn:03d}-{digest[:16]}",
                        "recordedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                        "provider": "replay-seed",
                        "route": "anthropic-messages",
                        "transport": "http",
                        "model": key["model"],
                        "tags": ["channel9", "seed", "toolloop", "sandbox"],
                        "note": "synthetic tool-loop seed generated by the "
                                "real-chain gateway from sandbox traffic; "
                                "contains no user data",
                    },
                    "interactions": [{
                        "transport": "http",
                        "turn": turn,
                        "track": "main",
                        "request": {"method": "POST", "url": path,
                                    "body": json.dumps({
                                        "model": key["model"],
                                        "system": key["system"],
                                        "messages": key["messages"],
                                        "tools": key["tools"],
                                        "stream": body.get("stream", True),
                                    })},
                        "response": {"status": 200,
                                     "headers": {"content-type": "text/event-stream"},
                                     "body": seed_text,
                                     "frames": frames_from_schedule(schedule)},
                    }],
                }
                os.makedirs(ARGS.record_dir, exist_ok=True)
                out = os.path.join(ARGS.record_dir,
                                   f"seed-turn-{turn:03d}-{digest[:16]}.json")
                try:
                    with open(out, "w", encoding="utf-8") as fh:
                        json.dump(cassette_doc, fh, indent=1)
                    with STATS.lock:
                        STATS.seeded += 1
                except OSError as err:
                    # A record-side failure must not kill the replay
                    # connection (the engine retries would burn turn
                    # ordinals); serve the scripted body regardless.
                    log("seed-record-error", error=str(err), cassette=out, turn=turn)
                ctype = "text/event-stream" if body.get("stream") else "application/json"
                self._serve_schedule(200, ctype, schedule)
                log("seeded", sha256=digest, cassette=out, pace=ARGS.pace["mode"],
                    frames=len(schedule), turn=turn)
                return
        STATS.note_miss(digest)
        if ARGS.dump_misses:
            os.makedirs(ARGS.dump_misses, exist_ok=True)
            with open(os.path.join(ARGS.dump_misses, f"miss-{digest[:16]}.json"), "w",
                      encoding="utf-8") as fh:
                json.dump({"sha256": digest, "path": path, "turn": turn,
                           "shape": shape, "normalized": key, "raw": body}, fh, indent=1)
        log("miss", sha256=digest, path=path, model=body.get("model"), turn=turn)
        self._diagnostic(digest, key, path)

    # -- POST ----------------------------------------------------------------
    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path
        length = int(self.headers.get("content-length") or 0)
        raw = self.rfile.read(length) if length else b"{}"
        try:
            body = json.loads(raw)
        except ValueError:
            self._send(400, b'{"error":"replay-gateway: body is not JSON"}')
            return
        redactions = [(a, b) for a, b in ARGS.redact]
        key, digest = normalize_request(body, redactions)
        log("request", path=path, model=body.get("model"), sha256=digest,
            stream=bool(body.get("stream")), bytes=len(raw),
            match=ARGS.match)

        # count_tokens side probe (anthropic SDK): answer a cheap estimate.
        if path.endswith("/count_tokens"):
            self._send(200, json.dumps({"input_tokens": max(1, len(raw) // 4)}).encode())
            return

        # W7 turn-anchored mode: aux calls keep digest matching; main
        # loop calls ride the turn ordinal + shape key.
        if ARGS.match == "turn" and not _is_aux_request(key):
            self._do_turn_post(path, body, key, digest)
            return

        hit = CORPUS.lookup(digest)
        if hit:
            _rank, cassette, inter = hit
            self._serve_interaction(digest, cassette, inter)
            return

        # Miss: optionally seed (sandbox-only bootstrap; see --seed-reply).
        STATS.note_miss(digest)
        if ARGS.seed_reply and ARGS.record_dir and key["model"]:
            # W3 hardening: title-generator requests (ref & port share the
            # `You are a title generator…` system prompt) get their OWN seed
            # text so the rendered session title never contains the main
            # turn's reply needle.
            seed_path = ARGS.seed_reply
            if ARGS.seed_title and _is_title_request(key):
                seed_path = ARGS.seed_title
            seed_body = open(seed_path, "rb").read()
            seed_text = seed_body.decode("utf-8", "replace")
            # W5: the seed cassette records the ACTIVE schedule as v2
            # frames (instant pace → one zero-delay frame = the v1
            # whole-body shape semantically; synthetic pace → the
            # deterministic tier timing).
            schedule = build_schedule(digest, seed_text, ARGS.pace)
            cassette = {
                "version": 2,
                "metadata": {
                    "name": "seeded/" + digest[:16],
                    "recordedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "provider": "replay-seed",
                    "route": "anthropic-messages",
                    "transport": "http",
                    "model": key["model"],
                    "tags": ["channel9", "seed", "sandbox"],
                    "note": "synthetic seed generated by the real-chain "
                            "gateway from sandbox traffic; contains no user data",
                },
                "interactions": [{
                    "transport": "http",
                    "request": {"method": "POST", "url": path,
                                "body": json.dumps({
                                    "model": key["model"],
                                    "system": key["system"],
                                    "messages": key["messages"],
                                    "tools": key["tools"],
                                    "stream": body.get("stream", True),
                                })},
                    "response": {"status": 200,
                                 "headers": {"content-type": "text/event-stream"},
                                 "body": seed_text,
                                 "frames": frames_from_schedule(schedule)},
                }],
            }
            os.makedirs(ARGS.record_dir, exist_ok=True)
            out = os.path.join(ARGS.record_dir, f"seed-{digest[:16]}.json")
            with open(out, "w", encoding="utf-8") as fh:
                json.dump(cassette, fh, indent=1)
            with STATS.lock:
                STATS.seeded += 1
            ctype = "text/event-stream" if body.get("stream") else "application/json"
            self._serve_schedule(200, ctype, schedule)
            log("seeded", sha256=digest, cassette=out, pace=ARGS.pace["mode"],
                frames=len(schedule))
            return
        if ARGS.dump_misses:
            os.makedirs(ARGS.dump_misses, exist_ok=True)
            with open(os.path.join(ARGS.dump_misses, f"miss-{digest[:16]}.json"), "w",
                      encoding="utf-8") as fh:
                json.dump({"sha256": digest, "path": path, "normalized": key,
                           "raw": body}, fh, indent=1)
        log("miss", sha256=digest, path=path, model=body.get("model"))
        self._diagnostic(digest, key, path)


def main():
    global ARGS, CORPUS, LOG
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--corpus", action="append", default=[])
    parser.add_argument("--log")
    parser.add_argument("--dump-misses")
    parser.add_argument("--redact", action="append", default=[],
                        help="FROM:TO text redaction in normalization")
    parser.add_argument("--seed-reply", help="SSE/JSON body served for misses "
                        "(bootstrap recording mode)")
    parser.add_argument("--seed-title", help="distinct seed body for "
                        "title-generator-shaped misses (W3 hardening: keeps "
                        "the main-turn reply needle and the session title "
                        "text distinguishable)")
    parser.add_argument("--record-dir", help="where seed cassettes are written")
    parser.add_argument("--pace", default="instant",
                        help="instant | frames | synthetic[:seed=N][:ttft=MS][:tps=T] "
                             "(W5 timing fidelity; default instant)")
    parser.add_argument("--match", default="digest", choices=["digest", "turn"],
                        help="digest = normalized-content hash (default); turn = "
                             "W7 turn-anchored matching for tool-loop sessions "
                             "(aux calls keep digest matching; main loop keyed by "
                             "turn ordinal + tool-result-blanked shape)")
    parser.add_argument("--seed-turns", dest="seed_turns",
                        help="turn-script dir for --match turn bootstrap: "
                             "turn-000.sse, turn-001.sse, ... served for unknown "
                             "ordinals and recorded into --record-dir with turn tags")
    args = parser.parse_args()
    ARGS = args
    ARGS.pace = parse_pace(args.pace)

    redactions = []
    for spec in args.redact:
        frm, _, to = spec.partition(":")
        redactions.append((frm, to))
    ARGS.redact = redactions

    if args.log:
        LOG = open(args.log, "a", encoding="utf-8", buffering=1)

    CORPUS = Corpus(args.corpus or [], redactions)
    global TURNCORPUS
    TURNCORPUS = TurnCorpus(CORPUS)
    log("corpus-loaded", dirs=args.corpus, interactions=CORPUS.count,
        unique=len(CORPUS.index), match=args.match,
        turns=len(TURNCORPUS.turns))

    server = ThreadingHTTPServer((args.host, args.port), Handler)
    port = server.server_address[1]
    # The harness's readiness line.
    print(f"READY host={args.host} port={port}", flush=True)
    log("listening", host=args.host, port=port)
    server.serve_forever()


if __name__ == "__main__":
    main()
