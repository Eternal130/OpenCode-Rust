#!/usr/bin/env python3
"""Channel 9 real-chain replay gateway.

The ONLY stub point in the real-chain harness (W1 design, approved
2026-11-17): it speaks the real provider wire protocol (anthropic
messages SSE first, openai chat completions second) on HTTP, matches
each incoming request by a normalized-content hash (model + system +
messages + tools) against a cassette corpus, and replays the recorded
response body byte-for-byte in the original frame order. A miss is a
strict 404 with a diagnostic body (nearest-neighbor matching is a
later-wave concern); misses are dumped for corpus seeding.

Corpus sources (--corpus, repeatable, later dirs override earlier):
  * committed ref HttpRecorder cassettes
    (crates/oc-ai/test-fixtures/recordings — request context + real
    response bodies, no user data)
  * a local real-traffic corpus dir (git-ignored; the privacy iron
    rule from `recorded-local` applies)
  * a committed synthetic seed corpus (tools/diff/realchain/corpus —
    generated by this gateway's --seed mode from sandbox traffic only)

Cassette format (v1, same shape as the ref HttpRecorder cassettes):
  { "version": 1, "metadata": {...}, "interactions": [
      { "request": { "method": "POST", "url": ..., "body": "<json>" },
        "response": { "status": 200, "headers": {...}, "body": "<sse>" } } ] }

Cassette format (v2, W5 timing fidelity): the response may additionally
carry `frames: [{blob, delay_ms}]` — the body split per SSE event with
the inter-frame delay captured at record time (a v1 whole-body
cassette still replays: it is read compatibly with NO timing). The
concatenated frame blobs equal the v1 body byte-for-byte.

Seed cassettes written by --seed-reply/--record-dir store the
NORMALIZED request object (post-redaction) plus the seed response, so
strict replays of equivalent (redacted-equal) requests hit. W5: when a
pace schedule is active the generated seed cassette records the
schedule as v2 `frames`, so timing survives cassette round-trips.

Pacing (--pace MODE, W5):
  * instant   — no pacing (default; the fast T9 battery shape)
  * frames    — replay cassette v2 `frames` delays where present
                (a body without frames falls back to instant)
  * synthetic:seed=N[:ttft=MS][:tps=T] — a DETERMINISTIC synthetic
                schedule (seed-corpus determinism; the same schedule is
                served to BOTH pair ends, so differential fairness is
                preserved: same schedule = I/O identical INCLUDING
                timing). Tiers: TTFT one of 300/1500/4000 ms and TPS
                one of 20/60/120 tok/s, chosen per request digest from
                sha256(digest + seed) — or pinned with the explicit
                ttft=/tps= params (the P1/P2 scenario pins).

Usage:
  replay_gateway.py --port 0 --corpus DIR [--corpus DIR ...] \
      [--log FILE] [--dump-misses DIR] [--redact FROM:TO] ... \
      [--seed-reply FILE] [--record-dir DIR] [--strict/--no-strict] \
      [--pace instant|frames|synthetic:...]
      [--match digest|turn] [--seed-turns DIR]
"""

# W7 -- turn-anchored matching (--match turn, the gateway v4). The
# digest key cannot replay a TOOL-LOOP session: turn k+1's request
# embeds the sandbox-executed tool_result of turn k, whose content
# (file paths, timings, output noise) can never equal the recorded
# one. Turn mode keys the MAIN-loop calls by their session turn
# ordinal instead:
#   * classification — title/summarization calls (the aux track) are
#     shape-detected and keep DIGEST matching (they are deterministic);
#     every other provider call is a main-loop turn,
#   * cross-environment key — the turn ordinal plus the request's
#     LARGE SHAPE (model + system + the message/tool sequence with
#     every tool_result CONTENT blanked to __TOOLRESULT__: sandbox
#     execution never participates in matching),
#   * conflict fallback — a shape mismatch on the turn's cassette
#     first re-scans the other turns for an exact shape hit
#     (counter drift), then replays the turn's own cassette with a
#     logged turn-shape-conflict event; strict 404 only when the
#     ordinal itself is unknown.
# Cassettes carry the tags on the interaction object: {"turn": <int>,
# "track": "main"|"aux"} (the --seed-turns bootstrap writes them).

