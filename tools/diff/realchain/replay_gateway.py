# Family preference (design: anthropic families first, openai chat second).
FAMILY_RANK = [
    ("anthropic-messages", 0),
    ("anthropic-messages-cache", 0),
    ("anthropic-compatible-messages", 1),
    ("openai-compatible-chat", 2),
    ("-chat", 3),
    ("anthropic", 0),
]


def family_rank(path: str) -> int:
    for needle, rank in FAMILY_RANK:
        if needle in path:
            return rank
    return 9


def _is_title_request(key) -> bool:
    """Title-generator heuristic: the shared ref/port title system prompt
    (`You are a title generator…`) identifies the session-title call."""
    system = key.get("system")
    if isinstance(system, str):
        return "title generator" in system.lower()
    if isinstance(system, list):
        return any(
            "title generator" in _canon(part).lower()
            for part in system
        )
    return False


class Corpus:
    def __init__(self, dirs, redactions):
        self.index = {}  # digest -> (rank, cassette_path, interaction)
        self.keys = {}   # digest -> normalized key (for shape re-keying)
        # W7: turn-tagged interactions collected INDEPENDENTLY of the
        # digest dedup — a turn cassette whose request digest collides
        # with an older untagged recording (the plain hello turn and
        # the tool-loop turn 0 normalize identically) must not lose
        # its turn tag to the rank contest.
        self.tagged = []  # (turn, digest, key, path, interaction)
        self.count = 0
        for corpus_dir in dirs:
            for root, _dirs, files in os.walk(corpus_dir):
                for name in sorted(files):
                    if not name.endswith(".json"):
                        continue
                    path = os.path.join(root, name)
                    try:
                        with open(path, encoding="utf-8") as fh:
                            doc = json.load(fh)
                        interactions = doc.get("interactions") or ([doc] if doc.get("request") else [])
                    except (OSError, ValueError) as err:
                        print(f"corpus: skip {path}: {err}", file=sys.stderr)
                        continue
                    for inter in interactions:
                        req = (inter or {}).get("request") or {}
                        raw = req.get("body")
                        if not isinstance(raw, str):
                            continue
                        try:
                            body = json.loads(raw)
                        except ValueError:
                            continue
                        if not isinstance(body, dict) or "model" not in body:
                            continue
                        key, digest = normalize_request(body, redactions)
                        rank = family_rank(path)
                        prev = self.index.get(digest)
                        if prev is None or rank < prev[0]:
                            self.index[digest] = (rank, path, inter)
                            self.keys[digest] = key
                        turn = (inter or {}).get("turn")
                        if isinstance(turn, int):
                            self.tagged.append((turn, digest, key, path, inter))
                        self.count += 1

    def lookup(self, digest):
        hit = self.index.get(digest)
        return hit


