#!/usr/bin/env python3
"""Channel 9 real-chain replay gateway.

The ONLY stub point in the real-chain harness (W1 design, approved
2026-11-17): it speaks the real provider wire protocol (anthropic
messages SSE first, openai chat completions second) on HTTP, matches
each incoming request by a normalized-content hash (model + system +
messages + tools) against a cassette corpus, and replays the recorded
response body byte-for-byte in the original frame order. A miss is a
strict 404 with a diagnostic body (nearest-neighbor matching is a
later-wave concern); misses are dumped for corpus seeding.

Corpus sources (--corpus, repeatable, later dirs override earlier):
  * committed ref HttpRecorder cassettes
    (crates/oc-ai/test-fixtures/recordings — request context + real
    response bodies, no user data)
  * a local real-traffic corpus dir (git-ignored; the privacy iron
    rule from `recorded-local` applies)
  * a committed synthetic seed corpus (tools/diff/realchain/corpus —
    generated by this gateway's --seed mode from sandbox traffic only)

Cassette format (v1, same shape as the ref HttpRecorder cassettes):
  { "version": 1, "metadata": {...}, "interactions": [
      { "request": { "method": "POST", "url": ..., "body": "<json>" },
        "response": { "status": 200, "headers": {...}, "body": "<sse>" } } ] }

Seed cassettes written by --seed-reply/--record-dir store the
NORMALIZED request object (post-redaction) plus the seed response, so
strict replays of equivalent (redacted-equal) requests hit.

Usage:
  replay_gateway.py --port 0 --corpus DIR [--corpus DIR ...] \
      [--log FILE] [--dump-misses DIR] [--redact FROM:TO] ... \
      [--seed-reply FILE] [--record-dir DIR] [--strict/--no-strict]
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import sys
import threading
import time
import urllib.parse
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

# ---------------------------------------------------------------------------
# Normalization
# ---------------------------------------------------------------------------

# Fields stripped from the matched sub-objects before hashing: volatile
# per-request knobs that do not change the semantic request context.
VOLATILE_TOP = ("stream", "max_tokens", "temperature", "top_p", "top_k",
                "stop_sequences", "metadata", "user", "parallel_tool_calls",
                "tool_choice", "seed", "presence_penalty", "frequency_penalty",
                "response_format", "service_tier", "reasoning_effort")
VOLATILE_MSG = ("cache_control",)  # prompt-cache breakpoints are transport
VOLATILE_TOOL = ("cache_control",)


# The engine's system prompt embeds "Today's date: Mon Nov 16 2026" —
# redact weekday-month-day-year shapes so seeds stay stable across days.
DATE_RE = re.compile(
    r"\b(?:Mon|Tue|Wed|Thu|Fri|Sat|Sun) "
    r"(?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec) \d{1,2} \d{4}\b"
)


def _canon(value) -> str:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def _strip(obj, volatile):
    if isinstance(obj, dict):
        return {k: _strip(v, volatile) for k, v in obj.items() if k not in volatile}
    if isinstance(obj, list):
        return [_strip(v, volatile) for v in obj]
    return obj


def normalize_request(body: dict, redactions):
    """model + system + messages + tools, canonically hashed.

    `redactions` is a list of (from, to) text substitutions applied to
    every string in the structure (the harness passes its sandbox root
    so PID-unique absolute paths hash equal across runs).
    """
    def redact(value):
        if isinstance(value, str):
            for frm, to in redactions:
                value = value.replace(frm, to)
            return DATE_RE.sub("__DATE__", value)
        if isinstance(value, dict):
            return {k: redact(v) for k, v in value.items()}
        if isinstance(value, list):
            return [redact(v) for v in value]
        return value

    key = {
        "model": body.get("model"),
        "system": _strip(redact(body.get("system")), VOLATILE_TOP),
        "messages": _strip(redact(body.get("messages")), VOLATILE_MSG),
        "tools": _strip(redact(body.get("tools")), VOLATILE_TOOL),
    }
    digest = hashlib.sha256(_canon(key).encode()).hexdigest()
    return key, digest


# ---------------------------------------------------------------------------
# Corpus index
# ---------------------------------------------------------------------------

# Family preference (design: anthropic families first, openai chat second).
FAMILY_RANK = [
    ("anthropic-messages", 0),
    ("anthropic-messages-cache", 0),
    ("anthropic-compatible-messages", 1),
    ("openai-compatible-chat", 2),
    ("-chat", 3),
    ("anthropic", 0),
]


def family_rank(path: str) -> int:
    for needle, rank in FAMILY_RANK:
        if needle in path:
            return rank
    return 9


def _is_title_request(key) -> bool:
    """Title-generator heuristic: the shared ref/port title system prompt
    (`You are a title generator…`) identifies the session-title call."""
    system = key.get("system")
    if isinstance(system, str):
        return "title generator" in system.lower()
    if isinstance(system, list):
        return any(
            "title generator" in _canon(part).lower()
            for part in system
        )
    return False


class Corpus:
    def __init__(self, dirs, redactions):
        self.index = {}  # digest -> (rank, cassette_path, interaction)
        self.count = 0
        for corpus_dir in dirs:
            for root, _dirs, files in os.walk(corpus_dir):
                for name in sorted(files):
                    if not name.endswith(".json"):
                        continue
                    path = os.path.join(root, name)
                    try:
                        with open(path, encoding="utf-8") as fh:
                            doc = json.load(fh)
                        interactions = doc.get("interactions") or ([doc] if doc.get("request") else [])
                    except (OSError, ValueError) as err:
                        print(f"corpus: skip {path}: {err}", file=sys.stderr)
                        continue
                    for inter in interactions:
                        req = (inter or {}).get("request") or {}
                        raw = req.get("body")
                        if not isinstance(raw, str):
                            continue
                        try:
                            body = json.loads(raw)
                        except ValueError:
                            continue
                        if not isinstance(body, dict) or "model" not in body:
                            continue
                        key, digest = normalize_request(body, redactions)
                        rank = family_rank(path)
                        prev = self.index.get(digest)
                        if prev is None or rank < prev[0]:
                            self.index[digest] = (rank, path, inter)
                        self.count += 1

    def lookup(self, digest):
        hit = self.index.get(digest)
        return hit


# ---------------------------------------------------------------------------
# Gateway
# ---------------------------------------------------------------------------

class Stats:
    def __init__(self):
        self.lock = threading.Lock()
        self.requests = 0
        self.hits = 0
        self.misses = 0
        self.seeded = 0
        self.miss_digests = []

    def note_hit(self):
        with self.lock:
            self.hits += 1

    def note_miss(self, digest):
        with self.lock:
            self.misses += 1
            if digest not in self.miss_digests:
                self.miss_digests.append(digest)

    def snapshot(self):
        with self.lock:
            return dict(requests=self.hits + self.misses, hits=self.hits,
                        misses=self.misses, seeded=self.seeded,
                        corpus=self.corpus_size, miss_digests=list(self.miss_digests))


STATS = Stats()
CORPUS = None          # type: Corpus | None
ARGS = None
LOG = None
LOG_LOCK = threading.Lock()


def log(event: str, **fields):
    line = json.dumps({"t": round(time.time(), 3), "event": event, **fields},
                      ensure_ascii=False)
    with LOG_LOCK:
        stream = LOG if LOG else sys.stdout
        print(line, file=stream, flush=True)


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def log_message(self, fmt, *args):  # silence default stderr chatter
        pass

    # -- helpers ----------------------------------------------------------
    def _send(self, status, body: bytes, content_type="application/json"):
        self.send_response(status)
        self.send_header("content-type", content_type)
        self.send_header("content-length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)
        self.wfile.flush()

    def _diagnostic(self, digest, key, path):
        diag = {
            "error": "replay-gateway: no cassette matched (strict mode)",
            "request_sha256": digest,
            "normalized": {
                "model": key["model"],
                "message_count": len(key["messages"] or []),
                "tool_count": len(key["tools"] or []),
                "system": (key["system"] if isinstance(key["system"], str)
                           else _canon(key["system"])[:400]),
            },
            "path": path,
            "hint": "seed with --seed-reply/--record-dir, or extend --corpus",
        }
        self._send(404, json.dumps(diag, indent=2).encode())

    # -- GET ---------------------------------------------------------------
    def do_GET(self):
        parsed = urllib.parse.urlparse(self.path)
        if parsed.path == "/__stats":
            STATS.corpus_size = CORPUS.count if CORPUS else 0
            self._send(200, json.dumps(STATS.snapshot(), indent=2).encode())
            return
        if parsed.path.rstrip("/").endswith("/models"):
            # A tiny model list keeps SDK probes alive; the harness asserts
            # on the SERVER's model API, never here.
            self._send(200, json.dumps({"data": []}).encode())
            return
        self._send(404, b'{"error":"replay-gateway: unknown GET route"}')

    # -- POST ----------------------------------------------------------------
    def do_POST(self):
        parsed = urllib.parse.urlparse(self.path)
        path = parsed.path
        length = int(self.headers.get("content-length") or 0)
        raw = self.rfile.read(length) if length else b"{}"
        try:
            body = json.loads(raw)
        except ValueError:
            self._send(400, b'{"error":"replay-gateway: body is not JSON"}')
            return
        redactions = [(a, b) for a, b in ARGS.redact]
        key, digest = normalize_request(body, redactions)
        log("request", path=path, model=body.get("model"), sha256=digest,
            stream=bool(body.get("stream")), bytes=len(raw))

        # count_tokens side probe (anthropic SDK): answer a cheap estimate.
        if path.endswith("/count_tokens"):
            self._send(200, json.dumps({"input_tokens": max(1, len(raw) // 4)}).encode())
            return

        hit = CORPUS.lookup(digest)
        if hit:
            _rank, cassette, inter = hit
            resp = inter.get("response") or {}
            resp_body = (resp.get("body") or "").encode()
            ctype = (resp.get("headers") or {}).get("content-type", "application/json")
            if isinstance(resp_body, str):
                resp_body = resp_body.encode()
            # normalize the transport framing headers; keep the body exact.
            self.send_response(resp.get("status", 200))
            self.send_header("content-type", ctype)
            self.send_header("content-length", str(len(resp_body)))
            self.end_headers()
            self.wfile.write(resp_body)
            self.wfile.flush()
            STATS.note_hit()
            log("hit", sha256=digest, cassette=cassette, status=resp.get("status"))
            return

        # Miss: optionally seed (sandbox-only bootstrap; see --seed-reply).
        STATS.note_miss(digest)
        if ARGS.seed_reply and ARGS.record_dir and key["model"]:
            # W3 hardening: title-generator requests (ref & port share the
            # `You are a title generator…` system prompt) get their OWN seed
            # text so the rendered session title never contains the main
            # turn's reply needle.
            seed_path = ARGS.seed_reply
            if ARGS.seed_title and _is_title_request(key):
                seed_path = ARGS.seed_title
            seed_body = open(seed_path, "rb").read()
            cassette = {
                "version": 1,
                "metadata": {
                    "name": "seeded/" + digest[:16],
                    "recordedAt": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
                    "provider": "replay-seed",
                    "route": "anthropic-messages",
                    "transport": "http",
                    "model": key["model"],
                    "tags": ["channel9", "seed", "sandbox"],
                    "note": "synthetic seed generated by the real-chain "
                            "gateway from sandbox traffic; contains no user data",
                },
                "interactions": [{
                    "transport": "http",
                    "request": {"method": "POST", "url": path,
                                "body": json.dumps({
                                    "model": key["model"],
                                    "system": key["system"],
                                    "messages": key["messages"],
                                    "tools": key["tools"],
                                    "stream": body.get("stream", True),
                                })},
                    "response": {"status": 200,
                                 "headers": {"content-type": "text/event-stream"},
                                 "body": seed_body.decode("utf-8", "replace")},
                }],
            }
            os.makedirs(ARGS.record_dir, exist_ok=True)
            out = os.path.join(ARGS.record_dir, f"seed-{digest[:16]}.json")
            with open(out, "w", encoding="utf-8") as fh:
                json.dump(cassette, fh, indent=1)
            with STATS.lock:
                STATS.seeded += 1
            ctype = "text/event-stream" if body.get("stream") else "application/json"
            self._send(200, seed_body, ctype)
            log("seeded", sha256=digest, cassette=out)
            return
        if ARGS.dump_misses:
            os.makedirs(ARGS.dump_misses, exist_ok=True)
            with open(os.path.join(ARGS.dump_misses, f"miss-{digest[:16]}.json"), "w",
                      encoding="utf-8") as fh:
                json.dump({"sha256": digest, "path": path, "normalized": key,
                           "raw": body}, fh, indent=1)
        log("miss", sha256=digest, path=path, model=body.get("model"))
        self._diagnostic(digest, key, path)


def main():
    global ARGS, CORPUS, LOG
    parser = argparse.ArgumentParser()
    parser.add_argument("--port", type=int, default=0)
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--corpus", action="append", default=[])
    parser.add_argument("--log")
    parser.add_argument("--dump-misses")
    parser.add_argument("--redact", action="append", default=[],
                        help="FROM:TO text redaction in normalization")
    parser.add_argument("--seed-reply", help="SSE/JSON body served for misses "
                        "(bootstrap recording mode)")
    parser.add_argument("--seed-title", help="distinct seed body for "
                        "title-generator-shaped misses (W3 hardening: keeps "
                        "the main-turn reply needle and the session title "
                        "text distinguishable)")
    parser.add_argument("--record-dir", help="where seed cassettes are written")
    args = parser.parse_args()
    ARGS = args

    redactions = []
    for spec in args.redact:
        frm, _, to = spec.partition(":")
        redactions.append((frm, to))
    ARGS.redact = redactions

    if args.log:
        LOG = open(args.log, "a", encoding="utf-8", buffering=1)

    CORPUS = Corpus(args.corpus or [], redactions)
    log("corpus-loaded", dirs=args.corpus, interactions=CORPUS.count,
        unique=len(CORPUS.index))

    server = ThreadingHTTPServer((args.host, args.port), Handler)
    port = server.server_address[1]
    # The harness's readiness line.
    print(f"READY host={args.host} port={port}", flush=True)
    log("listening", host=args.host, port=port)
    server.serve_forever()


if __name__ == "__main__":
    main()
