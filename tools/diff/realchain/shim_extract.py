#!/usr/bin/env python3
"""W7 layer 2 — the PATH-shim fast-execution extractor.

A tool-loop session's bash tool calls are replayed through PATH shims:
the cassette carries (bash command → recorded output) pairs — the
response's `tool_use` block names the command, the NEXT request's
`tool_result` carries the sandbox-executed output — and this tool
emits a shim directory the harness puts FIRST on the sandbox PATH.
A shim recognizes the FULL command line (token-wise prefix match,
longest recorded match wins) and instantly writes the recorded
stdout/stderr with the recorded exit code.

File-editing tools (edit/write) do NOT shim: they ride the real
sandbox filesystem (fast and deterministic by construction).

Outputs (under --out DIR):
  shims/<word>        executable stub for each recorded command's
                      first word (all stubs are hardlinks to
                      shims/.shimrun.py, which dispatches on argv0)
  shims/.shimrun.py   the dispatcher
  shims/_data/<word>.json  the recorded cases for that word
  shims/_real/<word>  the pre-shim PATH resolution of <word> (only
                      with --fallthrough real; --resolve-from PATH)

Fall-through policy for an unmatched command line (--fallthrough):
  * fail (default) — exit 127 with a diagnostic on stderr (the
    deterministic fast lane: an uncovered command is a corpus gap).
  * real            — exec the REAL binary recorded under _real/
    (the shim dir must have been assembled while the real tool was
    still resolvable; a missing _real entry is a hard 126).

Usage:
  shim_extract.py --cassette FILE [--cassette FILE ...] --out DIR \
      [--fallthrough fail|real] [--resolve-from PATH]
  shim_extract.py --spec FILE --out DIR [...]      # direct case list:
      # [{"command": "cargo test", "stdout": "...", "stderr": "",
      #   "exit_code": 0}, ...]
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import sys

SHIMRUN = '''#!/usr/bin/env python3
"""W7 PATH-shim dispatcher (generated by shim_extract.py)."""
import json
import os
import sys

name = os.path.basename(sys.argv[0])
shim_dir = os.path.dirname(os.path.abspath(__file__))
cases = []
data = os.path.join(shim_dir, "_data", name + ".json")
if os.path.isfile(data):
    with open(data, encoding="utf-8") as fh:
        cases = json.load(fh)

argv = sys.argv[1:]
actual = " ".join([name] + argv)

def prefix_tokens(recorded, actual):
    r = recorded.split()
    a = actual.split()
    return len(r) <= len(a) and a[:len(r)] == r

best = None
for case in cases:
    if prefix_tokens(case.get("command", ""), actual):
        if best is None or len(case["command"]) > len(best["command"]):
            best = case

if best is None:
    policy = "__FALLTHROUGH__"
    if policy == "real":
        real = os.path.join(shim_dir, "_real", name)
        if os.path.isfile(real) and os.access(real, os.X_OK):
            os.execv(real, [real] + argv)
        sys.stderr.write(
            "shim %s: no recorded case for %r and no _real fallback\\n"
            % (name, actual))
        sys.exit(126)
    sys.stderr.write(
        "shim %s: no recorded case for %r (fail-fast; extend the corpus)\\n"
        % (name, actual))
    sys.exit(127)

out = sys.stdout
err = sys.stderr
code = int(best.get("exit_code", 0) or 0)
# Keep the writes atomic-ish per stream so a full recorded body lands.
err.write(best.get("stderr", "") or "")
err.flush()
out.write(best.get("stdout", "") or "")
out.flush()
sys.exit(code)
'''


def _sse_tool_uses(body_text):
    """(tool_use_id, name, input) triples from an SSE response body."""
    out = []
    pending = {}
    for line in body_text.splitlines():
        if not line.startswith("data:"):
            continue
        payload = line[5:].strip()
        if not payload:
            continue
        try:
            doc = json.loads(payload)
        except ValueError:
            continue
        if not isinstance(doc, dict):
            continue
        block = doc.get("content_block")
        if isinstance(block, dict) and block.get("type") == "tool_use":
            pending[(doc.get("index"), block.get("id"))] = {
                "id": block.get("id"),
                "name": block.get("name"),
                "input_text": "",
            }
        delta = doc.get("delta")
        if isinstance(delta, dict) and delta.get("type") == "input_json_delta":
            # LATENT (registered, W7 review minor): the accumulation is
            # NOT index-keyed — with PARALLEL tool_use blocks whose
            # inputs stream as multi-chunk partial_json, every pending
            # state appends every chunk (cross-pollution). The corpus
            # shape (one tool_use per message, whole-JSON single-chunk
            # input) is unaffected; keying on doc["index"] is the fix
            # the day a parallel-blocks cassette shows up.
            for state in pending.values():
                state["input_text"] += delta.get("partial_json") or ""
    for state in pending.values():
        try:
            inputs = json.loads(state["input_text"] or "{}")
        except ValueError:
            inputs = {}
        out.append((state["id"], state["name"], inputs))
    return out


def _request_tool_results(body_text):
    """{tool_use_id: content-text} from a request body's messages."""
    try:
        body = json.loads(body_text)
    except (TypeError, ValueError):
        return {}
    out = {}
    messages = body.get("messages") if isinstance(body, dict) else None
    if not isinstance(messages, list):
        return out

    def walk(value):
        if isinstance(value, dict):
            if value.get("type") == "tool_result":
                content = value.get("content")
                text = ""
                if isinstance(content, str):
                    text = content
                elif isinstance(content, list):
                    text = "".join(
                        part.get("text", "") for part in content
                        if isinstance(part, dict))
                out[value.get("tool_use_id")] = text
            for child in value.values():
                walk(child)
        elif isinstance(value, list):
            for child in value:
                walk(child)

    walk(messages)
    return out


EXIT_TAIL_RE = re.compile(r"\n?Exit code (\d+)\s*$")


def extract_cases(cassettes):
    """(command, stdout, exit_code) cases from cassette pairs."""
    cases = []
    for path in cassettes:
        try:
            with open(path, encoding="utf-8") as fh:
                doc = json.load(fh)
        except (OSError, ValueError) as err:
            print(f"cassette: skip {path}: {err}", file=sys.stderr)
            continue
        interactions = doc.get("interactions") or []
        results = {}
        for inter in interactions:
            req_raw = (inter or {}).get("request", {}).get("body")
            if isinstance(req_raw, str):
                results.update(_request_tool_results(req_raw))
        for inter in interactions:
            resp_body = (inter or {}).get("response", {}).get("body")
            if not isinstance(resp_body, str):
                continue
            for tool_id, name, inputs in _sse_tool_uses(resp_body):
                if name not in ("bash", "execute", "shell"):
                    continue
                command = inputs.get("command")
                if not isinstance(command, str) or not command.strip():
                    continue
                output = results.get(tool_id, "")
                code = 0
                match = EXIT_TAIL_RE.search(output)
                if match:
                    code = int(match.group(1))
                    output = output[:match.start()]
                cases.append({"command": command.strip(),
                              "stdout": output,
                              "stderr": "",
                              "exit_code": code})
    return cases


def write_shims(out_dir, cases, fallthrough, resolve_from):
    shim_dir = os.path.join(out_dir, "shims")
    os.makedirs(os.path.join(shim_dir, "_data"), exist_ok=True)
    dispatcher = os.path.join(shim_dir, ".shimrun.py")
    with open(dispatcher, "w", encoding="utf-8") as fh:
        fh.write(SHIMRUN.replace("__FALLTHROUGH__", repr(fallthrough)))
    os.chmod(dispatcher, 0o755)
    by_word = {}
    for case in cases:
        word = case["command"].split()[0]
        by_word.setdefault(word, []).append(case)
    for word, word_cases in sorted(by_word.items()):
        with open(os.path.join(shim_dir, "_data", f"{word}.json"), "w",
                  encoding="utf-8") as fh:
            json.dump(word_cases, fh, indent=1)
        stub = os.path.join(shim_dir, word)
        if os.path.exists(stub):
            os.remove(stub)
        os.link(dispatcher, stub)
        os.chmod(stub, 0o755)
        if fallthrough == "real":
            real = shutil.which(word, path=resolve_from)
            if real:
                real_dir = os.path.join(shim_dir, "_real")
                os.makedirs(real_dir, exist_ok=True)
                target = os.path.join(real_dir, word)
                if not os.path.exists(target):
                    os.symlink(real, target)
    print(f"shims: {len(cases)} cases / {len(by_word)} commands -> {shim_dir}")
    for word in sorted(by_word):
        for case in by_word[word]:
            print(f"  {case['command']!r} -> exit {case['exit_code']}, "
                  f"{len(case['stdout'])} bytes")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cassette", action="append", default=[])
    parser.add_argument("--spec", help="JSON file: list of "
                        "{command, stdout, stderr?, exit_code?}")
    parser.add_argument("--out", required=True)
    parser.add_argument("--fallthrough", choices=["fail", "real"], default="fail")
    parser.add_argument("--resolve-from", dest="resolve_from",
                        default=os.environ.get("PATH", ""),
                        help="PATH used to resolve real binaries for "
                             "--fallthrough real (default $PATH)")
    args = parser.parse_args()
    cases = []
    if args.spec:
        with open(args.spec, encoding="utf-8") as fh:
            loaded = json.load(fh)
        for case in loaded:
            cases.append({"command": case["command"],
                          "stdout": case.get("stdout", ""),
                          "stderr": case.get("stderr", ""),
                          "exit_code": int(case.get("exit_code", 0) or 0)})
    cases.extend(extract_cases(args.cassette))
    if not cases:
        parser.error("no cases: pass --spec and/or --cassette")
    write_shims(args.out, cases, args.fallthrough, args.resolve_from)


if __name__ == "__main__":
    main()
