#!/usr/bin/env python3
''''exec python3 -- "$0" "$@" # '''
r"""G-27 — vendored ACP drift detection.

``third_party/agent-client-protocol`` is crates.io ``agent-client-protocol``
3.3.0 with ONE local change (the ``preserve_order`` default-feature removal,
see the comment at the bottom of the vendored ``Cargo.toml``). Nothing
enforced that "exactly upstream + exactly the recorded local changes"
invariant — a silent edit to the vendored sources would ride every build
with no provenance. This guard enforces it:

  1. Source the PRISTINE upstream 3.3.0 sources:
       a. ``ACP_PRISTINE_DIR`` env (an already-extracted crate tree), then
       b. the local cargo registry cache
          (``$CARGO_HOME``/``~/.cargo/registry/src/*/agent-client-protocol-3.3.0``),
       c. else download the ``.crate`` tarball from static.crates.io —
          checksum-pinned (``CRATE_SHA256``); ``--offline`` refuses this leg.
          Manual fallback (no network, no cargo): download
          https://static.crates.io/crates/agent-client-protocol/agent-client-protocol-3.3.0.crate
          verify the sha256 below, extract it, and point ACP_PRISTINE_DIR
          at the extracted ``agent-client-protocol-3.3.0/`` directory.
  2. Compute the local-changes patch (pristine → vendored, metadata files
     the registry adds removed from scope). If
     ``third_party/agent-client-protocol/LOCAL_CHANGES.patch`` does not
     exist yet, extract it there and exit 2 (commit it); ``--update``
     regenerates it intentionally (exit 0).
  3. APPLY the committed patch to a copy of the pristine tree and diff the
     result against the vendored tree. Any residual difference is drift
     (exit 1): the vendored tree changed without the patch being updated.

Stdlib only (the §9.1 guard convention). Exit codes: 0 clean / 1 drift /
2 guard error (missing inputs, patch applier mismatch, uncommitted new
patch).

Usage:
  python3 tools/guards/acp_drift.py [--update] [--offline] [-v]
"""

import argparse
import difflib
import hashlib
import os
import shutil
import sys
import tarfile
import tempfile
import urllib.request
from pathlib import Path

VERSION = "3.3.0"
CRATE = f"agent-client-protocol-{VERSION}"
CRATE_URL = f"https://static.crates.io/crates/agent-client-protocol/{CRATE}.crate"
# sha256 of the .crate tarball (computed from the registry cache; the same
# pin makes the download leg tamper-evident offline or on).
CRATE_SHA256 = "02898d848a20eb09b8a392e85bb3a4c79dba01d369758185d102b001362a60da"

REPO = Path(__file__).resolve().parent.parent.parent
VENDORED = REPO / "third_party" / "agent-client-protocol"
PATCH = VENDORED / "LOCAL_CHANGES.patch"

# Registry-side metadata that never belongs to the vendored tree (skipped
# on the pristine side; their absence in the vendored tree is not drift).
PRISTINE_ONLY = {".cargo-ok", ".cargo_vcs_info.json", "Cargo.toml.orig"}

# Generated on both sides (the vendored tree's lockfile is regenerated by
# the workspace, so it is not part of the recorded local changes); the
# guard checks source provenance, not lockfile churn.
OUT_OF_SCOPE = {"Cargo.lock", "LOCAL_CHANGES.patch"}


def log(verbose: bool, message: str) -> None:
    if verbose:
        print(f"acp-drift: {message}")


# --------------------------------------------------------------------------
# step 1 — pristine sources
# --------------------------------------------------------------------------

def registry_candidates() -> list[Path]:
    roots = []
    cargo_home = os.environ.get("CARGO_HOME")
    if cargo_home:
        roots.append(Path(cargo_home))
    roots.append(Path.home() / ".cargo")
    found = []
    for root in roots:
        src = root / "registry" / "src"
        if src.is_dir():
            found.extend(sorted(src.glob(f"*/{CRATE}")))
    return [path for path in found if (path / "Cargo.toml").is_file()]


def download_pristine(dest: Path) -> Path:
    print(f"acp-drift: downloading pinned {CRATE}.crate (sha256 {CRATE_SHA256[:16]}…)")
    archive = dest / f"{CRATE}.crate"
    urllib.request.urlretrieve(CRATE_URL, archive)  # noqa: S310 - pinned https URL
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    if digest != CRATE_SHA256:
        raise RuntimeError(
            f"{CRATE}.crate sha256 mismatch: got {digest}, pinned {CRATE_SHA256}"
        )
    with tarfile.open(archive) as tar:
        tar.extractall(dest, filter="data")
    extracted = dest / CRATE
    if not (extracted / "Cargo.toml").is_file():
        raise RuntimeError(f"archive layout unexpected: no Cargo.toml under {extracted}")
    return extracted


def locate_pristine(tmp: Path, offline: bool, verbose: bool) -> Path:
    override = os.environ.get("ACP_PRISTINE_DIR")
    if override:
        path = Path(override)
        if not (path / "Cargo.toml").is_file():
            raise RuntimeError(f"ACP_PRISTINE_DIR={path} has no Cargo.toml")
        log(verbose, f"pristine from ACP_PRISTINE_DIR: {path}")
        return path
    for candidate in registry_candidates():
        log(verbose, f"pristine from registry cache: {candidate}")
        return candidate
    if offline:
        raise RuntimeError(
            "no pristine sources in the registry cache and --offline refuses the "
            "download; run without --offline, or fetch the .crate manually "
            f"(sha256 {CRATE_SHA256}) and point ACP_PRISTINE_DIR at it"
        )
    return download_pristine(tmp)


# --------------------------------------------------------------------------
# step 2 — the local-changes patch (deterministic pristine → vendored diff)
# --------------------------------------------------------------------------

def tree_files(root: Path, skip: set[str] = frozenset()) -> dict[str, bytes]:
    files = {}
    for path in sorted(root.rglob("*")):
        if path.is_dir() or path.is_symlink():
            continue
        rel = path.relative_to(root).as_posix()
        if rel in skip or path.name in skip:
            continue
        files[rel] = path.read_bytes()
    return files


def render_patch(pristine: Path) -> str:
    """Unified diff pristine → vendored over text files, stable output."""
    left = tree_files(pristine, skip=PRISTINE_ONLY | OUT_OF_SCOPE)
    right = tree_files(VENDORED, skip=OUT_OF_SCOPE)
    chunks = []
    for rel in sorted(set(left) | set(right)):
        old = left.get(rel)
        new = right.get(rel)
        if old == new:
            continue
        old_lines = old.decode().splitlines(keepends=True) if old is not None else []
        new_lines = new.decode().splitlines(keepends=True) if new is not None else []
        if old is not None and new is not None and b"\x00" in old + new:
            raise RuntimeError(f"binary drift is out of scope: {rel}")
        fromfile = f"a/{rel}" if old is not None else "/dev/null"
        tofile = f"b/{rel}" if new is not None else "/dev/null"
        diff = list(
            difflib.unified_diff(
                old_lines, new_lines, fromfile=fromfile, tofile=tofile, lineterm=""
            )
        )
        # difflib keeps the source '\n' on content lines; normalize so the
        # patch is exactly one line per entry (round-trips through
        # str.splitlines() in the applier).
        chunks.append(
            "".join(line if line.endswith("\n") else line + "\n" for line in diff)
        )
    header = (
        f"# Local changes to vendored {CRATE} (crates.io) vs the pristine\n"
        f"# tarball (sha256 {CRATE_SHA256}). Regenerate with\n"
        f"#   python3 tools/guards/acp_drift.py --update\n"
    )
    return header + "".join(chunks)


# --------------------------------------------------------------------------
# step 3 — apply the committed patch to pristine, diff vs vendored
# --------------------------------------------------------------------------

def apply_patch(pristine: Path, patch_text: str, target: Path) -> list[str]:
    """Apply our own generated unified diffs (the only format the guard
    commits). Returns the list of touched relative paths; raises on any
    structural mismatch (a hand-edited or foreign patch is a guard error).
    """
    shutil.copytree(pristine, target)
    touched: list[str] = []
    rel: str | None = None
    old_lines: list[str] | None = None
    new_lines: list[str] | None = None
    deleted = False

    def flush() -> None:
        nonlocal rel, old_lines, new_lines, deleted
        if rel is None:
            return
        out = target / rel
        if deleted:  # '+++ /dev/null' — the file is removed
            out.unlink()
        else:
            assert old_lines is not None
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_text("".join(old_lines))
        touched.append(rel)
        rel, old_lines, new_lines, deleted = None, None, None, False

    lines = patch_text.splitlines()
    index = 0
    while index < len(lines):
        line = lines[index]
        if line.startswith("#") or not line.strip():
            index += 1
            continue
        if line.startswith("--- "):
            flush()
            fromfile = line[4:]
            index += 1
            if index >= len(lines) or not lines[index].startswith("+++ "):
                raise RuntimeError(f"patch: '---' without '+++' near {fromfile}")
            tofile = lines[index][4:]
            if fromfile == "/dev/null":
                rel = tofile.removeprefix("b/")
                old_lines = []
            else:
                rel = fromfile.removeprefix("a/")
                old_lines = (target / rel).read_text().splitlines(keepends=True)
            new_lines = [] if tofile == "/dev/null" else None
            deleted = tofile == "/dev/null"
            index += 1
            continue
        if line.startswith("@@"):
            if rel is None:
                raise RuntimeError("patch: hunk before any '---' header")
            parsed = line[3:].split("@@", 1)[0].split()
            old_start = abs(int(parsed[0].split(",")[0]))
            hunk_old: list[str] = []
            hunk_new: list[str] = []
            index += 1
            while index < len(lines) and (
                lines[index][:1] in (" ", "-", "+", "\\")
            ):
                hunk = lines[index]
                if hunk.startswith("\\"):  # "\ No newline at end of file"
                    index += 1
                    continue
                if hunk.startswith(" "):
                    hunk_old.append(hunk[1:] + "\n")
                    hunk_new.append(hunk[1:] + "\n")
                elif hunk.startswith("-"):
                    hunk_old.append(hunk[1:] + "\n")
                else:
                    hunk_new.append(hunk[1:] + "\n")
                index += 1
            # Position: the hunk's old lines must appear at old_start
            # (difflib emits exact positions; a mismatch means the patch
            # was generated against a different pristine).
            assert old_lines is not None
            begin = max(old_start - 1, 0)  # "@@ -0,0" (new file) starts at 0
            if old_lines[begin : begin + len(hunk_old)] != hunk_old:
                raise RuntimeError(
                    f"patch: hunk does not apply to pristine {rel} at line {old_start}"
                )
            old_lines[begin : begin + len(hunk_old)] = hunk_new
            continue
        raise RuntimeError(f"patch: unexpected line: {line!r}")
    flush()
    return touched


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update", action="store_true", help="regenerate LOCAL_CHANGES.patch")
    parser.add_argument("--offline", action="store_true", help="never download the .crate")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()

    if not (VENDORED / "Cargo.toml").is_file():
        print(f"acp-drift: missing vendored tree at {VENDORED}", file=sys.stderr)
        return 2

    with tempfile.TemporaryDirectory(prefix="acp-drift-") as raw:
        try:
            pristine = locate_pristine(Path(raw), offline=args.offline, verbose=args.verbose)
            expected = render_patch(pristine)
        except RuntimeError as error:
            print(f"acp-drift: {error}", file=sys.stderr)
            return 2

        if args.update:
            PATCH.write_text(expected)
            print(f"acp-drift: regenerated {PATCH.relative_to(REPO)} — commit it")
            return 0

        if not PATCH.is_file():
            PATCH.write_text(expected)
            print(
                f"acp-drift: extracted {PATCH.relative_to(REPO)} (none was committed); "
                "commit it and re-run",
                file=sys.stderr,
            )
            return 2

        committed = PATCH.read_text()
        if committed != expected:
            print(
                "acp-drift: LOCAL_CHANGES.patch is stale vs the vendored tree — "
                "regenerate with `python3 tools/guards/acp_drift.py --update` "
                "and commit (with a ledger note) if the change is intentional",
                file=sys.stderr,
            )
            for line in difflib.unified_diff(
                committed.splitlines(), expected.splitlines(),
                fromfile="committed LOCAL_CHANGES.patch", tofile="vendored tree",
                lineterm="",
            ):
                print(line, file=sys.stderr)
            return 1

        # The patch matches the computed diff; prove it end-to-end by
        # applying the COMMITTED bytes to the pristine copy and diffing
        # against the vendored tree (catches a hand-massaged patch that
        # textually equals nothing real, and any applier drift).
        staged = Path(raw) / "staged"
        try:
            apply_patch(pristine, committed, staged)
        except RuntimeError as error:
            print(f"acp-drift: {error}", file=sys.stderr)
            return 2
        residual = []
        for rel, blob in tree_files(staged, skip=PRISTINE_ONLY | OUT_OF_SCOPE).items():
            want = (VENDORED / rel)
            if not want.is_file() or want.read_bytes() != blob:
                residual.append(rel)
        extra = [
            rel for rel in tree_files(VENDORED, skip=OUT_OF_SCOPE)
            if not (staged / rel).is_file()
        ]
        if residual or extra:
            print(
                "acp-drift: DRIFT — vendored third_party/agent-client-protocol "
                "differs from upstream 3.3.0 + LOCAL_CHANGES.patch:",
                file=sys.stderr,
            )
            for rel in sorted(set(residual) | set(extra)):
                print(f"  {rel}", file=sys.stderr)
            return 1

    print("acp-drift: ok — vendored tree is upstream 3.3.0 + LOCAL_CHANGES.patch")
    return 0


if __name__ == "__main__":
    sys.exit(main())
