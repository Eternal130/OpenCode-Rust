/**
 * Fuzzy-order corpus generator — pins the Rust fuzzysort port
 * (crates/oc-tui/src/components/dialog_select/fuzzy.rs) against the
 * REFERENCE fuzzysort 3.1.0 (the version opencode v2.0.24 ships).
 *
 * Runs the same ranking the dialog does (`ui/dialog-select.tsx`):
 * fuzzysort.go(needle, options, { keys: [title, category, searchText],
 * scoreFn: r => r[0].score*2 + r[1].score + r[2].score, threshold })
 * over the PRODUCTION palette registry (titles/categories/ids from the
 * reference app tables — mirrored in Rust PALETTE_COMMANDS), and emits
 * the expected ranked command-id order per query.
 *
 * Usage: bun fuzzy_corpus.ts > crates/oc-tui/src/components/dialog_select/fuzzy_corpus.json
 */
import fuzzysort from "/tmp/opencode/ref/packages/tui/node_modules/fuzzysort/fuzzysort.js"

// Mirrors PALETTE_COMMANDS in crates/oc-tui/src/components/command_palette.rs
// (keep the two tables in sync — the Rust test asserts the mirror).
const registry = [
  ["session.list", "Switch session", "Session"],
  ["session.new", "New session", "Session"],
  ["session.clear", "Clear session", "Session"],
  ["open.menu", "Open session or project", "Session"],
  ["session.tab.close", "Close tab", "Session"],
  ["session.tab.reopen", "Reopen closed tab", "Session"],
  ["session.share", "Share session", "Session"],
  ["session.rename", "Rename session", "Session"],
  ["session.timeline", "Jump to message", "Session"],
  ["session.fork", "Fork session", "Session"],
  ["session.compact", "Compact session", "Session"],
  ["session.undo", "Undo previous message", "Session"],
  ["session.redo", "Redo", "Session"],
  ["session.move", "Manage workspaces", "Session"],
  ["model.list", "Switch model", "Agent"],
  ["agent.list", "Switch agent", "Agent"],
  ["mcp.list", "MCP servers", "Agent"],
  ["variant.cycle", "Variant cycle", "Agent"],
  ["variant.list", "Switch model variant", "Agent"],
  ["provider.connect", "Connect an integration", "Integration"],
  ["opencode.settings", "Open settings", "System"],
  ["opencode.status", "View status", "System"],
  ["server.pair", "Pair device", "System"],
  ["location.reload", "Reload configuration", "System"],
  ["opencode.debug", "View debug info", "System"],
  ["theme.switch", "Switch theme", "System"],
  ["help.show", "Help", "System"],
  ["docs.open", "Open docs", "System"],
  ["app.exit", "Exit the app", "System"],
  ["app.console", "Toggle console", "System"],
]

// The palette's option construction: searchText = [id, description].join(" ")
// with no description on the app commands → the id alone.
const options = registry.map(([id, title, category]) => ({
  id,
  title,
  category,
  searchText: id,
}))

const queries = [
  "rename",
  "new",
  "model",
  "theme",
  "session",
  "se",
  "switch",
  "m",
  "compact session",
  "switch m",
  "sess",
  "open",
  "tab",
  "share",
  "app",
  "swch",
]

const out = {
  provenance:
    "generated by tools/parity/tui-dump/fuzzy_corpus.ts against the reference fuzzysort 3.1.0 (opencode v2.0.24 node_modules)",
  threshold: 0.7,
  targets: registry.map(([id, title, category]) => ({ id, title, category })),
  queries: queries.map((query) => {
    const results = fuzzysort.go(query, options, {
      keys: ["title", "category", "searchText"],
      scoreFn: (r) => r[0].score * 2 + r[1].score + r[2].score,
      threshold: 0.7,
    })
    return { query, expected: results.map((result) => result.obj.id) }
  }),
}

console.log(JSON.stringify(out, null, 1))
